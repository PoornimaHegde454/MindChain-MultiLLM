#!/usr/bin/env python3
"""
Apply working models configuration to model_selector.py
This script reads the working_models_config.py file and updates model_selector.py
to only include working models.
"""

import json
import sys
import re
from pathlib import Path

def load_working_config():
    """Load the working models configuration"""
    try:
        # Try to load from JSON results file first (more reliable)
        json_file = Path("provider_model_test_results.json")
        if json_file.exists():
            with open(json_file, "r") as f:
                results = json.load(f)
            
            # Get working models from results
            working_models = {}
            working_routing_rules = {}
            
            # Load model selector to get full model definitions
            from app.core.model_selector import ModelSelector
            model_selector = ModelSelector()
            
            # Filter to only working models
            for model_name, model_result in results.get("models", {}).items():
                if model_result.get("success", False):
                    # Get full model definition from model selector
                    if model_name in model_selector.models:
                        working_models[model_name] = model_selector.models[model_name]
            
            # Update routing rules to use only working models
            for (domain, complexity), model_name in model_selector.routing_rules.items():
                if model_name in working_models:
                    working_routing_rules[(domain, complexity)] = model_name
                else:
                    # Find alternative
                    model_info = model_selector.models.get(model_name, {})
                    model_domains = model_info.get("capabilities", {}).get("domains", [])
                    model_complexity = model_info.get("capabilities", {}).get("complexity", [])
                    
                    alternative = None
                    for working_model in working_models.keys():
                        working_info = model_selector.models.get(working_model, {})
                        working_domains = working_info.get("capabilities", {}).get("domains", [])
                        working_complexity_levels = working_info.get("capabilities", {}).get("complexity", [])
                        
                        if domain in working_domains and complexity in working_complexity_levels:
                            alternative = working_model
                            break
                    
                    if not alternative and working_models:
                        for preferred in ["llama-3.1-8b-instant", "llama-3.1-8b", "gpt-oss-20b", "phi-3-mini"]:
                            if preferred in working_models:
                                alternative = preferred
                                break
                        if not alternative:
                            alternative = list(working_models.keys())[0]
                    
                    if alternative:
                        working_routing_rules[(domain, complexity)] = alternative
            
            return working_models, working_routing_rules
        
        # Fallback to Python config file
        config_file = Path("working_models_config.py")
        if not config_file.exists():
            print("❌ Error: provider_model_test_results.json or working_models_config.py not found!")
            print("   Please run test_providers_models.py first to generate the configuration.")
            return None, None
        
        # Parse the config file
        with open(config_file, "r") as f:
            content = f.read()
        
        # Extract WORKING_MODELS dictionary
        models_match = re.search(r'WORKING_MODELS = ({.*?})', content, re.DOTALL)
        if not models_match:
            print("❌ Error: Could not parse WORKING_MODELS from config file")
            return None, None
        
        # Evaluate the models dictionary (safe since it's generated by our script)
        models_str = models_match.group(1)
        working_models = eval(models_str)  # Safe eval of our own generated code
        
        # Extract WORKING_ROUTING_RULES
        rules_match = re.search(r'WORKING_ROUTING_RULES = ({.*?})', content, re.DOTALL)
        if not rules_match:
            print("❌ Error: Could not parse WORKING_ROUTING_RULES from config file")
            return None, None
        
        rules_str = rules_match.group(1)
        working_routing_rules = eval(rules_str)  # Safe eval of our own generated code
        
        return working_models, working_routing_rules
        
    except Exception as e:
        print(f"❌ Error loading working config: {str(e)}")
        import traceback
        traceback.print_exc()
        return None, None

def update_model_selector(working_models, working_routing_rules):
    """Update model_selector.py with only working models"""
    model_selector_file = Path("app/core/model_selector.py")
    
    if not model_selector_file.exists():
        print(f"❌ Error: {model_selector_file} not found!")
        return False
    
    # Read the current file
    with open(model_selector_file, "r") as f:
        content = f.read()
    
    # Create backup
    backup_file = model_selector_file.with_suffix(".py.backup")
    with open(backup_file, "w") as f:
        f.write(content)
    print(f"📄 Backup created: {backup_file}")
    
    # Replace the models dictionary
    models_start = content.find('self.models = {')
    if models_start == -1:
        print("❌ Error: Could not find 'self.models = {' in model_selector.py")
        return False
    
    # Find the end of the models dictionary
    models_end = models_start
    brace_count = 0
    in_string = False
    string_char = None
    
    for i in range(models_start + len('self.models = {'), len(content)):
        char = content[i]
        
        if char in ['"', "'"] and (i == 0 or content[i-1] != '\\'):
            if not in_string:
                in_string = True
                string_char = char
            elif char == string_char:
                in_string = False
                string_char = None
        
        if not in_string:
            if char == '{':
                brace_count += 1
            elif char == '}':
                brace_count -= 1
                if brace_count == 0:
                    models_end = i + 1
                    break
    
    if models_end == models_start:
        print("❌ Error: Could not find end of models dictionary")
        return False
    
    # Generate new models dictionary as string
    new_models_str = "self.models = {\n"
    for model_name, model_info in working_models.items():
        new_models_str += f'            "{model_name}": {{\n'
        for key, value in model_info.items():
            if isinstance(value, dict):
                # Format nested dict properly
                dict_str = json.dumps(value, indent=16)
                # Replace leading spaces to match indentation
                dict_str = dict_str.replace('\n', '\n                ')
                new_models_str += f'                "{key}": {dict_str},\n'
            elif isinstance(value, str):
                new_models_str += f'                "{key}": "{value}",\n'
            elif isinstance(value, list):
                list_str = json.dumps(value)
                new_models_str += f'                "{key}": {list_str},\n'
            else:
                new_models_str += f'                "{key}": {value},\n'
        new_models_str += "            },\n"
    new_models_str += "        }"
    
    # Replace models dictionary
    content = content[:models_start] + new_models_str + content[models_end:]
    
    # Replace routing rules
    routing_start = content.find('self.routing_rules = {')
    if routing_start != -1:
        routing_end = routing_start
        brace_count = 0
        in_string = False
        string_char = None
        
        for i in range(routing_start + len('self.routing_rules = {'), len(content)):
            char = content[i]
            
            if char in ['"', "'"] and (i == 0 or content[i-1] != '\\'):
                if not in_string:
                    in_string = True
                    string_char = char
                elif char == string_char:
                    in_string = False
                    string_char = None
            
            if not in_string:
                if char == '{':
                    brace_count += 1
                elif char == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        routing_end = i + 1
                        break
        
        if routing_end > routing_start:
            # Generate new routing rules
            new_routing_str = "self.routing_rules = {\n"
            for (domain, complexity), model_name in working_routing_rules.items():
                new_routing_str += f'            ("{domain}", "{complexity}"): "{model_name}",\n'
            new_routing_str += "        }"
            
            content = content[:routing_start] + new_routing_str + content[routing_end:]
    
    # Write updated content
    with open(model_selector_file, "w") as f:
        f.write(content)
    
    print(f"✅ Updated {model_selector_file} with working models only")
    return True

def main():
    """Main function"""
    print("=" * 70)
    print("Apply Working Models Configuration")
    print("=" * 70)
    
    # Load working configuration
    working_models, working_routing_rules = load_working_config()
    
    if working_models is None or working_routing_rules is None:
        return 1
    
    print(f"\n📊 Loaded configuration:")
    print(f"   Working models: {len(working_models)}")
    print(f"   Routing rules: {len(working_routing_rules)}")
    
    # Confirm with user
    print(f"\n⚠️  This will update app/core/model_selector.py to only include working models.")
    response = input("   Continue? (y/n): ").strip().lower()
    
    if response != 'y':
        print("❌ Cancelled by user")
        return 1
    
    # Update model selector
    if update_model_selector(working_models, working_routing_rules):
        print("\n✅ Successfully updated model_selector.py!")
        print("   A backup has been created at app/core/model_selector.py.backup")
        return 0
    else:
        print("\n❌ Failed to update model_selector.py")
        return 1

if __name__ == "__main__":
    try:
        exit_code = main()
        sys.exit(exit_code)
    except KeyboardInterrupt:
        print("\n\n⚠️  Operation interrupted by user")
        sys.exit(1)
    except Exception as e:
        print(f"\n\n❌ Fatal error: {str(e)}")
        import traceback
        traceback.print_exc()
        sys.exit(1)

